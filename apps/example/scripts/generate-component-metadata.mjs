import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'src/data/components.tsx');
const demosPath = path.join(root, 'src/data/demos');
const outputPath = path.join(root, 'src/data/components.generated.ts');
const signaturesPath = path.join(root, 'src/data/components.demo-signatures.generated.json');
// Blocks are documented and registered from the docs workspace, so their names
// and summaries are read from there rather than written a second time here.
const blocksSourcePath = path.resolve(root, '../docs/scripts/blocks.json');
const blocksOutputPath = path.join(root, 'src/data/blocks.generated.ts');
const sourceText = fs.readFileSync(sourcePath, 'utf8');
const source = ts.createSourceFile(
  sourcePath,
  sourceText,
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TSX
);

function initializer(parsed, name) {
  for (const statement of parsed.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (declaration.name.getText(parsed) === name) return declaration.initializer;
    }
  }
  throw new Error(`Could not find ${name} in ${parsed.fileName}`);
}

function stringProperty(parsed, object, name) {
  const property = object.properties.find(
    (candidate) =>
      ts.isPropertyAssignment(candidate) && candidate.name.getText(parsed) === name
  );
  if (!property || !ts.isPropertyAssignment(property) || !ts.isStringLiteralLike(property.initializer)) {
    throw new Error(`Every catalogue entry needs a string ${name}`);
  }
  return property.initializer.text;
}

const demoSources = fs.readdirSync(demosPath).filter((file) => file.endsWith('.tsx')).sort().map((file) => {
  const filename = path.join(demosPath, file);
  return ts.createSourceFile(filename, fs.readFileSync(filename, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
});
const components = demoSources.flatMap((parsed) => {
  const entries = initializer(parsed, 'ENTRIES');
  if (!entries || !ts.isArrayLiteralExpression(entries)) throw new Error(`${parsed.fileName}: ENTRIES must be an array literal`);
  return entries.elements.map((entry) => {
    if (!ts.isObjectLiteralExpression(entry)) throw new Error('Every catalogue entry must be an object');
    return {
      slug: stringProperty(parsed, entry, 'slug'),
      name: stringProperty(parsed, entry, 'name'),
      summary: stringProperty(parsed, entry, 'summary'),
      signature: createHash('sha256').update(entry.getText(parsed)).digest('hex'),
    };
  });
});
components.sort((a, b) => a.name.localeCompare(b.name));
if (new Set(components.map((entry) => entry.slug)).size !== components.length) {
  throw new Error('Catalogue slugs must be unique');
}

const chartSlugs = initializer(source, 'CHART_SLUGS');
if (!chartSlugs || !ts.isAsExpression(chartSlugs) || !ts.isArrayLiteralExpression(chartSlugs.expression)) {
  throw new Error('CHART_SLUGS must be a const array literal');
}
const charts = chartSlugs.expression.elements.map((entry) => {
  if (!ts.isStringLiteralLike(entry)) throw new Error('Every chart slug must be a string');
  return entry.text;
});
const componentSlugs = new Set(components.map((entry) => entry.slug));
for (const slug of charts) {
  if (!componentSlugs.has(slug)) throw new Error(`Unknown chart slug: ${slug}`);
}

const rows = components.map(({ signature: _signature, ...entry }) => `  ${JSON.stringify(entry)},`).join('\n');
const output = `// Generated by scripts/generate-component-metadata.mjs. Do not edit.\n\nexport const COMPONENTS = [\n${rows}\n] as const;\n\nexport type ComponentMetadata = (typeof COMPONENTS)[number];\nexport const COMPONENT_COUNT = COMPONENTS.length;\nexport const CHART_COUNT = ${charts.length};\n`;
const signatures = JSON.stringify(
  { generated: 'Run npm run metadata:generate --workspace=example; do not edit.', entries: components.map(({ slug, signature }) => ({ slug, signature })) },
  null,
  2
) + '\n';

const blocks = Object.entries(JSON.parse(fs.readFileSync(blocksSourcePath, 'utf8'))).map(
  ([slug, [name, summary]]) => ({ slug, name, summary })
);
const blockRows = blocks.map((entry) => `  ${JSON.stringify(entry)},`).join('\n');
const blocksOutput = `// Generated by scripts/generate-component-metadata.mjs from apps/docs/scripts/blocks.json. Do not edit.\n\nexport const BLOCK_METADATA = [${blockRows ? `\n${blockRows}\n` : ''}] as const;\n\nexport type BlockMetadata = (typeof BLOCK_METADATA)[number];\nexport type BlockSlug = BlockMetadata['slug'];\n`;

if (process.argv.includes('--check')) {
  if (
    !fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== output ||
    !fs.existsSync(signaturesPath) || fs.readFileSync(signaturesPath, 'utf8') !== signatures ||
    !fs.existsSync(blocksOutputPath) || fs.readFileSync(blocksOutputPath, 'utf8') !== blocksOutput
  ) {
    console.error('Component metadata is stale. Run `npm run metadata:generate --workspace=example`.');
    process.exit(1);
  }
  console.log(`component metadata: ${components.length} entries and ${blocks.length} blocks are current`);
} else {
  fs.writeFileSync(outputPath, output);
  fs.writeFileSync(signaturesPath, signatures);
  fs.writeFileSync(blocksOutputPath, blocksOutput);
  console.log(`component metadata: wrote ${components.length} entries and ${blocks.length} blocks`);
}
